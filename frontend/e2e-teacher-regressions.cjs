   await page.getByRole('button',{name:'展开对照',exact:true}).click();
   check('既有隔离回放仍可复核6/6到5/6',/6\/6/.test(await page.locator('.teacher-answer-body').innerText())&&/5\/6/.test(await page.locator('.teacher-answer-body').innerText()));
   check('回放明确非官方结果',/隔离副本用正式管线重算，非官方结果/.test(await page.locator('.teacher-answer-body').innerText()));
