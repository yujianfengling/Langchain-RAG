   await page.getByTestId('export-review').getByText('磁盘成果包与当前系统建议一致',{exact:true}).waitFor({timeout:30000});
   check('既有成果包复核仍可用',await page.getByTestId('export-review').getByText('磁盘成果包与当前系统建议一致',{exact:true}).isVisible());
   await page.goto(base+'/class-analytics?quizId=N02&classId=DC02&reviewBudget=2&planTheme=T02');
   await page.getByRole('heading',{name:'建议先讲',exact:true}).waitFor();
