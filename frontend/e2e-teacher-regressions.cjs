   await page.getByRole('button',{name:'查看 解一元一次不等式 的失分依据',exact:true}).click();
   check('N01未测不显示成零分',/本次未测/.test(await page.locator('.ant-drawer-content:visible').innerText()));
   await page.goto(base+'/class-analytics?quizId=N01&classId=DC02&planTheme=T01&reviewBudget=2');
   await page.locator('[data-testid^="lecture-choice-"]').first().waitFor({timeout:30000});
   check('切换班级生成该班真实两题',await page.locator('[data-testid^="lecture-choice-"]').count()===2);
   await page.locator('[data-testid^="lecture-choice-"]').first().getByRole('button').click();
   const ids=(await page.locator('.ant-drawer-content:visible').last().innerText()).match(/D\d{2}/g)||[];
   check('DC02下钻不混DC01学生',ids.length>0&&ids.every(id=>Number(id.slice(1))>=22));
   await answer('D01','Q015');
